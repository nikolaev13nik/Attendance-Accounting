CREATE TABLE users (
    id_user    INTEGER      NOT NULL,
    first_name VARCHAR(255),
    last_name  VARCHAR(255),
    password   VARCHAR(255),
    email      VARCHAR(255),
    tenant_id  INTEGER      NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (tenant_id, id_user)
);

CREATE TABLE user_roles (
    tenant_id INTEGER      NOT NULL,
    user_id   INTEGER      NOT NULL,
    roles     VARCHAR(255),
    CONSTRAINT uq_user_roles UNIQUE (tenant_id, user_id, roles),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (tenant_id, user_id) REFERENCES users (tenant_id, id_user)
        ON DELETE CASCADE
);

CREATE TABLE att_ac_tenant_mapping (
    tenant_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    company_name VARCHAR(255) NOT NULL,
    contact_name VARCHAR(255) NOT NULL,
    phone        VARCHAR(40)  NOT NULL,
    email        VARCHAR(255) NOT NULL,
    status       VARCHAR(15),
    CONSTRAINT pk_att_ac_tenant_mapping PRIMARY KEY (tenant_id),
    CONSTRAINT uq_att_ac_tenant_mapping_company_name UNIQUE (company_name)
);
